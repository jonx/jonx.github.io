function storedLanguage() {
  try {
    return localStorage.getItem("clipto-lang");
  } catch {
    return null;
  }
}
const requested =
  new URLSearchParams(location.search).get("lang") || storedLanguage();
export let language = requested === "en" ? "en" : "fr";
export const t = (text) => (language === "en" ? (english[text] ?? text) : text);

// Capture static interface text once; never traverse user input or generated previews.
const staticText = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (
    node.parentElement.closest(
      "script, style, textarea, #status, #source-origin",
    )
  )
    continue;
  const key = node.textContent.trim().replace(/\s+/g, " ");
  if (english[key]) staticText.push({ node, key });
}
const attributes = [];
for (const element of document.querySelectorAll(
  "[aria-label], [title], [placeholder]",
)) {
  for (const attr of ["aria-label", "title", "placeholder"]) {
    const value = element.getAttribute(attr);
    if (value && english[value]) attributes.push({ element, attr, value });
  }
}
export function setLanguage(next) {
  language = next === "en" ? "en" : "fr";
  document.documentElement.lang = language;
  for (const { node, key } of staticText)
    if (node.isConnected) {
      // Keep separating whitespace around icons and nested emphasis.
      node.textContent = node.textContent.replace(/\S(?:[\s\S]*\S)?/, t(key));
    }
  for (const { element, attr, value } of attributes)
    element.setAttribute(attr, t(value));
  document.title =
    language === "en"
      ? "ClipTo Web - Copy. Choose. Paste. - jkn.me"
      : "ClipTo Web - Copiez. Choisissez. Collez. - jkn.me";
  document.getElementById("language").textContent =
    language === "en" ? "Français" : "English";
  document.getElementById("language").lang = language === "en" ? "fr" : "en";
  document
    .getElementById("language")
    .setAttribute(
      "aria-label",
      language === "en" ? "Passer en français" : "Switch to English",
    );
  try {
    localStorage.setItem("clipto-lang", language);
  } catch {
    // Private mode or blocked storage: the choice lasts for this page only.
  }
  const url = new URL(location.href);
  if (language === "en") url.searchParams.set("lang", "en");
  else url.searchParams.delete("lang");
  history.replaceState(null, "", url);
}
setLanguage(language);
